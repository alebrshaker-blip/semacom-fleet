from sqlalchemy import Float, Integer, Text
from sqlalchemy.orm import Mapped, mapped_column

from core.database import Base, DictMixin


class MaintenanceOrder(DictMixin, Base):
    __tablename__ = "maintenance_orders"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    status: Mapped[str | None] = mapped_column(Text, server_default="open")
    type: Mapped[str] = mapped_column(Text, nullable=False)
    order_no: Mapped[str] = mapped_column(Text, unique=True, nullable=False)
    vehicle_code: Mapped[str | None] = mapped_column(Text)
    plate_number: Mapped[str | None] = mapped_column(Text)
    vehicle_id: Mapped[int | None] = mapped_column(Integer)
    expected_cost: Mapped[float | None] = mapped_column(Float, server_default="0")
    final_cost: Mapped[float | None] = mapped_column(Float, server_default="0")
    driver_id: Mapped[str | None] = mapped_column(Text)
    maintenance_type: Mapped[str | None] = mapped_column(Text)
    fault_description: Mapped[str | None] = mapped_column(Text)
    fault_cause: Mapped[str | None] = mapped_column(Text)
    severity: Mapped[str | None] = mapped_column(Text)
    technician_name: Mapped[str | None] = mapped_column(Text)
    expected_completion_time: Mapped[str | None] = mapped_column(Text)
    order_date: Mapped[str | None] = mapped_column(Text)
    workshop_name: Mapped[str | None] = mapped_column(Text)
    workshop_phone: Mapped[str | None] = mapped_column(Text)
    workshop_location: Mapped[str | None] = mapped_column(Text)
    send_reason: Mapped[str | None] = mapped_column(Text)
    send_datetime: Mapped[str | None] = mapped_column(Text)
    responsible_person: Mapped[str | None] = mapped_column(Text)
    expected_time: Mapped[str | None] = mapped_column(Text)
    notes: Mapped[str | None] = mapped_column(Text)
    driver_name: Mapped[str | None] = mapped_column(Text)
    reporter_name: Mapped[str | None] = mapped_column(Text)
    case_description: Mapped[str | None] = mapped_column(Text)
    has_injuries: Mapped[str | None] = mapped_column(Text)
    is_drivable: Mapped[str | None] = mapped_column(Text)
    official_notified: Mapped[str | None] = mapped_column(Text)
    emergency_location: Mapped[str | None] = mapped_column(Text)
    incident_datetime: Mapped[str | None] = mapped_column(Text)
    subject: Mapped[str | None] = mapped_column(Text)
    description: Mapped[str | None] = mapped_column(Text)
    causes: Mapped[str | None] = mapped_column(Text)
    other_details: Mapped[str | None] = mapped_column(Text)
    closure_date: Mapped[str | None] = mapped_column(Text)
    receipt_datetime: Mapped[str | None] = mapped_column(Text)
    closure_datetime: Mapped[str | None] = mapped_column(Text)
    closure_reason: Mapped[str | None] = mapped_column(Text)
    action_taken: Mapped[str | None] = mapped_column(Text)
    is_towed: Mapped[str | None] = mapped_column(Text)
    towing_party: Mapped[str | None] = mapped_column(Text)
    intervention_team: Mapped[str | None] = mapped_column(Text)
    treatment_details: Mapped[str | None] = mapped_column(Text)
    closing_notes: Mapped[str | None] = mapped_column(Text)
    spare_parts: Mapped[str | None] = mapped_column(Text)
    recommendation: Mapped[str | None] = mapped_column(Text)
    photo_before: Mapped[str | None] = mapped_column(Text)
    photo_after: Mapped[str | None] = mapped_column(Text)
    other_attachments: Mapped[str | None] = mapped_column(Text)

